'''
Exercício 3: sequência com intervalo

Nível: Básico.

Enunciado: Escreva um programa que imprima a seguinte sequência utilizando while:
5
10
15
20
25
30

Objetivo

Perceber que a atualização da variável de controle não precisa ocorrer sempre de um em um.

'''

number = 5

while number <= 30:
    print(number)
    number += 5